def build_outline_layout(facts: dict, roster: dict, site: dict, interior=None) -> dict:
    """``layout.build_layout``'s result, with every plate drawn to the outlines in ``site``.

    ``site``: ``{"source", "detail", "polygons_latlng", "holes_latlng", "street_bearing_deg",
    "address_latlng"}`` (see ``context.layout_site``). Raises ``ShapeError`` when the outlines
    cannot hold the record.
    """
    from ingest.unified.layout import (DOOR_H, DOOR_W, ELEVATOR_W, INTERIOR_MAX_UNITS, PROFILE, STAIR_RUN_M, WALKWAY_M,
                                       WINDOW_HEAD, WINDOW_SILL, _opening, _Walls, choose_archetype, generic_interior)

    use = facts.get("use_type") or "other"
    depth, corridor_w, default_area, _min_w = PROFILE.get(use, PROFILE["other"])
    archetype = choose_archetype(facts, roster)
    stories, hgt = roster["stories"], roster["storey_height_m"]
    levels = [Level(f, str(f), r((f - 1) * hgt), r(hgt), roster["height_source"]) for f in range(1, stories + 1)]
    slots = roster["slots"]
    with_interiors = use in ("apartment", "hotel") and sum(s["kind"] == "unit" for s in slots) <= INTERIOR_MAX_UNITS
    has_core = archetype == "central_core" or (archetype in ("double_loaded_corridor", "floor_stack") and (
        facts.get("has_elevator") is True or (facts.get("has_elevator") is None and stories >= 4)))
    cw = corridor_w if archetype != "bays" else 0.0

    frame = site_frame(site)
    outlines = frame["polygons"]
    blocks: dict[str, list[dict]] = defaultdict(list)
    for s in slots:
        blocks[s["block"]].append(s)
    keys = sorted(blocks, key=_natural) or [""]
    if len(outlines) != len(keys):
        if not slots and len(outlines) > 1:
            keys = [str(i + 1) for i in range(len(outlines))]
        else:
            raise ShapeError(f"count ({len(outlines)}) does not match the {len(keys)} buildings the units name")
    if any(p.area < MIN_OUTLINE_M2 for p in outlines):
        raise ShapeError(f"is too small to be the building ({min(p.area for p in outlines):.0f} m2)")

    def weight(s: dict) -> float:
        return float(s.get("area_m2") or default_area)

    # largest building to largest outline
    size = {k: sum(weight(s) for s in blocks.get(k, [])) for k in keys}
    order = sorted(keys, key=lambda k: (-size[k], _natural(k))) if len(keys) > 1 else keys
    outline_of = dict(zip(order, outlines))

    walls = _Walls()
    spaces: list[Space] = []
    links: list[Link] = []
    entrances: list[Entrance] = []
    notes: list[str] = []
    centre: dict[str, tuple] = {}
    stamped = generic = 0
    plate_area = outline_area = dropped = 0.0
    wing_count = 0
    scale_lo, scale_hi = float("inf"), 0.0
    ground: list[tuple[str, tuple, tuple]] = []  # per block: main entrance (space id, xy, outward)
    floor_spaces = 0

    def add(space: Space) -> Space:
        spaces.append(space)
        centre[space.id] = space.centroid
        return space

    def link(a: str, b: str, kind: str, xy=None, length: Optional[float] = None, floors: int = 0) -> None:
        if length is None:
            ca, cb = centre[a], centre[b]
            length = (math.dist(ca, xy) + math.dist(xy, cb)) if xy else math.dist(ca, cb)
        links.append(Link(a=a, b=b, kind=kind, evidence="template", length_m=r(length, 2), floors=floors,
                          xy=rp(xy) if xy else None))

    for bi, key in enumerate(keys):
        outline = outline_of[key]
        btag = f"b{bi + 1}"
        # the plate's own frame: turned so that its long side runs along x
        if len(keys) > 1:
            from ingest.unified.context import oriented_box

            ob = oriented_box(list(outline.exterior.coords))
            ang, (ocx, ocy) = math.radians(ob["axis_deg"]), ob["centre"]
        else:
            ang, ocx, ocy = 0.0, 0.0, 0.0
        ca_, sa_ = math.cos(ang), math.sin(ang)

        def to_model(p, ca_=ca_, sa_=sa_, ocx=ocx, ocy=ocy) -> tuple[float, float]:
            return (ocx + p[0] * ca_ - p[1] * sa_, ocy + p[0] * sa_ + p[1] * ca_)

        def to_plate(p, ca_=ca_, sa_=sa_, ocx=ocx, ocy=ocy) -> tuple[float, float]:
            dx, dy = p[0] - ocx, p[1] - ocy
            return (dx * ca_ + dy * sa_, -dx * sa_ + dy * ca_)

        P = _clean(shapely.transform(outline, lambda xy: np.array([to_plate(p) for p in xy])))
        if P is None:
            raise ShapeError("is not a usable polygon")
        fx, fy = frame["front"]
        front = (fx * ca_ + fy * sa_, -fx * sa_ + fy * ca_)
        items = blocks.get(key, [])
        per_floor: dict[int, list[dict]] = defaultdict(list)
        for s in items:
            per_floor[s["floor"]].append(s)
        busiest = max((len(v) for v in per_floor.values()), default=0)
        need = max((sum(weight(s) for s in v) for v in per_floor.values()), default=0.0)
        if need and P.area < MIN_AREA_SHARE * need:
            raise ShapeError(f"({P.area:.0f} m2) is far smaller than the units recorded on one floor ({need:.0f} m2)")
        # the corridor wall a unit should get: a unit about one and a half times as deep as it is wide
        unit_w = min(max(_min_w, math.sqrt(0.85 * P.area / busiest / 1.5)), 9.0) if busiest else _min_w
        plate = _Plate(P, depth, cw, archetype, has_core, busiest, front, stories, unit_w)
        outline_area += P.area
        wing_count += max(1, len(plate.corridors))
        block_entrances: list[Entrance] = []
        below: dict[str, str] = {}
        walk_id = None
        if archetype == "bays":  # the strip outside the front wall that every bay opens onto
            x0, y0, x1, y1 = P.bounds
            ys = (y1, y1 + WALKWAY_M) if front[1] > 0 else (y0 - WALKWAY_M, y0)
            walk_id = f"walk{bi + 1}"
            add(make_space(walk_id, 1, "walkway", "Frontage",
                           [to_model(p) for p in ((x0, ys[0]), (x1, ys[0]), (x1, ys[1]), (x0, ys[1]))], "template"))

        for lv in levels:
            f, z0 = lv.index, lv.z0
            regions, lobby, elevator = plate.variants[bool(has_core or f == 1)]
            polys: dict[str, Polygon] = {}
            kind_of: dict[str, str] = {}
            meta: dict[str, dict] = {}
            here: dict[str, str] = {}

            def put(sid: str, poly: Polygon, kind: str, label: str, fidelity: str = "template", **extra) -> None:
                polys[sid] = poly
                kind_of[sid] = kind
                meta[sid] = {"label": label, "fidelity": fidelity, **extra}

            for ci, poly in enumerate(plate.corridors):
                put(f"{btag}w{ci + 1}f{f}-cor", poly, "corridor", "Breezeway" if archetype == "garden_walkup" else "Corridor",
                    room_type="corridor")
            for si, poly in enumerate(plate.stairs):
                name = f"st{chr(65 + si)}"
                sid = f"{btag}w1f{f}-{name}"
                put(sid, poly, "stair", f"Stair {chr(65 + si)}", room_type="stairwell")
                here[name] = sid
            if elevator is not None:
                sid = f"{btag}w1f{f}-el"
                put(sid, elevator, "elevator", "Elevator", room_type="elevator")
                here["elevator"] = sid
            lobby_id = None
            if lobby is not None:
                lobby_id = f"{btag}w1f{f}-lob"
                label = ("Lobby" if f == 1 else "Elevator lobby") if has_core else "Entry"
                put(lobby_id, lobby, "lobby", label, room_type="lobby" if f == 1 else "corridor")

            # ---- units --------------------------------------------------------
            us = per_floor.get(f, [])
            got = _deal(us, regions, weight)
            unit_region: dict[str, dict] = {}
            for ri, reg in enumerate(regions):
                mine = got.get(ri) or []
                if not mine:
                    fid = f"{btag}f{f}-p{ri + 1}"
                    put(fid, reg["poly"], "floor", f"Floor {f} (no unit data)", "roster", room_type="unknown")
                    floor_spaces += 1
                    continue
                cuts = plate.cut((bool(has_core or f == 1), ri), reg, [weight(s) for s in mine])
                for s, poly in zip(mine, cuts):
                    s["_block"] = key
                    put(s["id"], poly, s["kind"], s["label"], raw_class=s.get("type") or "",
                        room_type="unit" if s["kind"] == "unit" else "suite", source_ref=s["id"],
                        attrs={"beds": s.get("beds"), "baths": s.get("baths"), "tenant": s.get("tenant"),
                               "floor_source": s.get("floor_source"),
                               "record_area_m2": round(s["area_m2"], 1) if s.get("area_m2") else None,
                               "scan": (s.get("scans") or [""])[0]})
                    unit_region[s["id"]] = reg
                    if s.get("area_m2"):
                        scale_lo, scale_hi = min(scale_lo, poly.area / s["area_m2"]), max(scale_hi, poly.area / s["area_m2"])

            for sid, poly in polys.items():
                m = dict(meta[sid])
                add(make_space(sid, f, kind_of[sid], m.pop("label"), [to_model(p) for p in _ring(poly)], m.pop("fidelity"),
                               block=key, **m))
                if f == 1:
                    plate_area += poly.area

            # ---- walls, doors, windows, links ---------------------------------
            shell = _shell_walls(polys)
            by_pair: dict[tuple, list] = defaultdict(list)
            outer: dict[str, list] = defaultdict(list)
            for a, b, (s1, s2) in shell:
                if s2 is None:
                    outer[s1].append((a, b))
                else:
                    by_pair[(s1, s2)].append((a, b))
            openings: dict[tuple, list] = defaultdict(list)
            circulation = [sid for sid in polys if kind_of[sid] in ("corridor", "lobby")]

            def shared(sid: str, others) -> Optional[tuple]:
                """Longest wall ``sid`` shares with any of ``others``: ``(length, a, b, other)``."""
                best = None
                for o in others:
                    for a, b in by_pair.get((min(sid, o), max(sid, o)), ()):
                        d = math.dist(a, b)
                        if best is None or d > best[0]:
                            best = (d, a, b, o)
                return best

            def door(sid: str, wall: tuple, kind: str, width: float, link_kind: str) -> None:
                _, a, b, other = wall
                at = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
                op = _opening(kind, a, b, at, width, z0, z0 + DOOR_H)
                if op is not None:
                    openings[(a, b)].append(op)
                link(sid, other, link_kind, xy=to_model(at))

            def outward(sid: str, a, b) -> tuple[float, float]:
                length = math.dist(a, b)
                nx, ny = (b[1] - a[1]) / length, -(b[0] - a[0]) / length
                if polys[sid].contains(SPoint((a[0] + b[0]) / 2 + nx * EPS, (a[1] + b[1]) / 2 + ny * EPS)):
                    nx, ny = -nx, -ny
                return nx, ny

            corridors = [sid for sid in polys if kind_of[sid] == "corridor"]
            for i, c1 in enumerate(corridors):  # corridors that meet are one space to walk through
                for c2 in corridors[i + 1:]:
                    wall = shared(c1, [c2])
                    if wall is not None:
                        link(c1, c2, "corridor", xy=to_model(((wall[1][0] + wall[2][0]) / 2, (wall[1][1] + wall[2][1]) / 2)))
            open_pairs = {(min(c1, c2), max(c1, c2)) for c1 in corridors for c2 in corridors if c1 != c2}
            for sid in polys:
                kind = kind_of[sid]
                if kind == "corridor":
                    continue
                if kind == "lobby":
                    wall = shared(sid, corridors) or shared(sid, [o for o in polys if o != sid])
                    if wall is not None:
                        door(sid, wall, "opening", 2.0, "opening")
                    continue
                if archetype == "bays":
                    continue
                reg = unit_region.get(sid)
                own = [f"{btag}w{reg['corr'] + 1}f{f}-cor"] if reg is not None and reg["corr"] is not None else []
                wall = shared(sid, own) if own else None
                if wall is None or wall[0] < 0.7:
                    wall = shared(sid, corridors) or wall
                if (wall is None or wall[0] < 0.7) and lobby_id:
                    wall = shared(sid, [lobby_id]) or wall
                if wall is None:  # cut off from every corridor: a door into the neighbour with the longest shared wall
                    wall = shared(sid, [o for o in polys if o != sid and kind_of[o] not in ("stair", "elevator")])
                if wall is None:
                    raise ShapeError("leaves a room with no wall to put a door in")
                if kind == "floor":
                    door(sid, wall, "opening", 2.0, "opening")
                elif kind == "elevator":
                    door(sid, wall, "doorway", 1.1, "door")
                else:
                    door(sid, wall, "doorway", DOOR_W, "door")

            # windows: on the outer walls of units and tenant suites (a stamped unit brings its own)
            child_done: set[str] = set()
            slot_of = {s["id"]: s for s in us}
            for sid in polys:
                if kind_of[sid] not in ("unit", "tenant"):
                    continue
                slot = slot_of.get(sid)
                children = None
                reg = unit_region.get(sid)
                if slot is not None and reg is not None and archetype != "bays" and (
                        (interior is not None and slot.get("scans")) or (with_interiors and slot["kind"] == "unit")):
                    fit = _inner_box(polys[sid], reg)
                    if fit is not None:
                        bx, to_local = fit

                        def move(p, to_local=to_local):
                            return to_model(to_local(p))

                        proxy = _MovedWalls(walls, move)
                        if interior is not None and slot.get("scans"):
                            children = interior(slot, bx, "S", f, z0, lv.height_m, proxy)
                        if children is not None:
                            stamped += 1
                            child_done.add(sid)
                        elif with_interiors and slot["kind"] == "unit":
                            children = generic_interior(slot, bx, "S", f, z0, proxy)
                            generic += 1
                        for child in children or []:
                            add(_move_space(child, move))
                if sid in child_done:
                    continue
                glass = sorted(outer.get(sid, ()), key=lambda ab: -math.dist(*ab))
                glass = [ab for ab in glass if math.dist(*ab) >= 1.5][:6] or [ab for ab in glass[:1] if math.dist(*ab) >= 0.9]
                for a, b in glass:
                    d = math.dist(a, b)
                    op = _opening("window", a, b, ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2), min(1.8, 0.45 * d),
                                  z0 + WINDOW_SILL, z0 + WINDOW_HEAD)
                    if op is not None:
                        openings[(a, b)].append(op)

            # ---- ways in (ground floor) ----------------------------------------
            if f == 1:
                def entrance(sid: str, name: str, width: float, listed: bool = True) -> Optional[tuple]:
                    best = None
                    for a, b in outer.get(sid, ()):
                        d = math.dist(a, b)
                        if d < 1.1:
                            continue
                        n = outward(sid, a, b)
                        mx, my = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
                        if plate.shell.contains(SPoint(mx + n[0] * 0.1, my + n[1] * 0.1)):
                            continue  # a wall onto a courtyard is not a way in from the street
                        key_ = (round(n[0] * front[0] + n[1] * front[1], 1), min(d, 6.0))
                        if best is None or key_ > best[0]:
                            best = (key_, a, b, n, (mx, my))
                    if best is None:
                        return None
                    _, a, b, n, at = best
                    op = _opening("doorway", a, b, at, width, z0, z0 + DOOR_H)
                    if op is not None:
                        openings[(a, b)].append(op)
                    nm = to_model((at[0] + n[0], at[1] + n[1]))
                    am = to_model(at)
                    out_ = (nm[0] - am[0], nm[1] - am[1])
                    norm = math.hypot(*out_) or 1.0
                    if listed:
                        block_entrances.append(Entrance("", f"{name}{' ' + key if key else ''}", sid, rp(am),
                                                        (r(out_[0] / norm, 9), r(out_[1] / norm, 9)), "template"))
                    return am

                if archetype == "bays":
                    for sid in polys:  # every bay opens onto the frontage; the first dozen doors are listed
                        at = entrance(sid, f"{meta[sid]['label']} front door", DOOR_W, listed=len(block_entrances) < 12)
                        if at is None:
                            wall = shared(sid, [o for o in polys if o != sid])
                            if wall is None:
                                raise ShapeError("leaves a bay with no outer wall")
                            door(sid, wall, "doorway", DOOR_W, "door")
                        else:
                            link(sid, walk_id, "door", xy=at)
                else:
                    if lobby_id:
                        entrance(lobby_id, "Lobby entrance" if has_core else "Main entrance", 1.6)
                    for name in sorted(k for k in here if k.startswith("st")):
                        entrance(here[name], f"Stair {name[-1]} entrance", DOOR_W)
                    if not block_entrances:  # no lobby and no stair on an outer wall: a door at the end of a corridor
                        for c in corridors:
                            if entrance(c, "Corridor entrance", DOOR_W):
                                break

            # ---- walls into the collector --------------------------------------
            for a, b, (s1, s2) in shell:
                if s2 is not None and (s1, s2) in open_pairs:
                    continue
                ops = openings.get((a, b), ())
                am, bm = to_model(a), to_model(b)
                if s2 is None:
                    walls.add(f, am, bm, s1, "facade", ops)
                else:
                    inner = "corridor" if {kind_of[s1], kind_of[s2]} & {"corridor", "lobby", "stair", "elevator"} else "side"
                    walls.add(f, am, bm, s1, inner, ops)
                    walls.add(f, am, bm, s2, inner)

            for name in sorted(here):
                if name in below:
                    link(below[name], here[name], "elevator" if name == "elevator" else "stairs",
                         length=STAIR_RUN_M if name != "elevator" else lv.height_m, floors=1)
            below = here

        dropped += plate.dropped
        if walk_id is not None:
            if block_entrances:
                ground.append((walk_id, block_entrances[0].xy, block_entrances[0].outward))
        elif block_entrances:
            ground.append((block_entrances[0].space_id, block_entrances[0].xy, block_entrances[0].outward))
        for e in block_entrances:
            entrances.append(replace(e, id=f"ent-{len(entrances) + 1}"))

    # ---- several buildings: a pad outside each main entrance, joined by walkways ----
    if len(keys) > 1 and len(ground) > 1:
        pads = []
        for i, (sid, xy, out_) in enumerate(ground):
            if sid.startswith("walk"):
                pads.append(sid)
                continue
            half = WALKWAY_M / 2
            cx, cy = xy[0] + out_[0] * (half + 0.3), xy[1] + out_[1] * (half + 0.3)
            tx, ty = -out_[1], out_[0]
            ring = [(cx + sx * half * out_[0] + sy * half * tx, cy + sx * half * out_[1] + sy * half * ty)
                    for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
            pid = f"walk{i + 1}"
            add(make_space(pid, 1, "walkway", "Walkway", ring, "template"))
            link(sid, pid, "door", xy=xy)
            pads.append(pid)
        joined = [pads[0]]
        for pid in pads[1:]:  # each pad to the nearest one already joined
            near = min(joined, key=lambda j: math.dist(centre[j], centre[pid]))
            link(near, pid, "walkway")
            joined.append(pid)

    # every room must be reachable on foot from a way in; an outline that leaves one cut off is not used
    top = {sp.id for sp in spaces if sp.parent is None}
    nbrs: dict[str, set[str]] = defaultdict(set)
    for ln in links:
        nbrs[ln.a].add(ln.b)
        nbrs[ln.b].add(ln.a)
    seen = {e.space_id for e in entrances} or set(list(top)[:1])
    queue = list(seen)
    while queue:
        for nb in nbrs[queue.pop()]:
            if nb not in seen:
                seen.add(nb)
                queue.append(nb)
    if top - seen:
        raise ShapeError(f"leaves {len(top - seen)} rooms that cannot be reached")
    if not entrances:
        raise ShapeError("leaves no outer wall for a way in")

    if roster["stats"].get("floor_spread"):
        notes.append(f"{roster['stats']['floor_spread']} unit(s) have no floor in their number; "
                     "they are spread evenly over the floors.")
    recorded = roster["stats"].get("storeys_recorded") or 0
    if recorded and stories > recorded:
        notes.append(f"Unit numbers name floors up to {stories}; the record lists {recorded} storeys. "
                     "The numbers on the doors are used.")
    source = site.get("source") or "a map"
    detail = f" ({site['detail']})" if site.get("detail") else ""
    if len(keys) > 1:
        notes.append(f"The outlines of the {len(keys)} buildings are taken from {source}{detail}. Which building is "
                     "which is assumed: the largest building in the record is drawn in the largest outline, and so on.")
    else:
        notes.append(f"The building's outline is taken from {source}{detail}; every floor is drawn to that outline.")
    notes.append("The interior is generated by rule from the property record: corridors, stairs, elevators, the lobby "
                 "and the walls between units are not measured.")
    if scale_hi and (scale_hi > 1.5 or scale_lo < 0.67):
        notes.append(f"Units are scaled to fill the outline while keeping their recorded proportions: they are drawn at "
                     f"{scale_lo:.1f} to {scale_hi:.1f} times their recorded areas.")
    if floor_spaces and slots:
        notes.append("Parts of a floor with no recorded unit are drawn as undivided areas.")
    if not with_interiors and use in ("apartment", "hotel"):
        notes.append("Unit interiors are left out for a property this large.")
    if slots:
        notes.append("Unit positions along each corridor are assumed (number order, alternating sides).")
    return {
        "archetype": archetype, "levels": levels, "spaces": spaces, "walls": walls.build(), "links": links,
        "entrances": entrances, "notes": notes,
        "stats": {"blocks": len(keys), "wings": wing_count, "units_with_stamped_interior": stamped,
                  "units_with_generic_interior": generic,
                  "shape": {"kind": "outline", "source": source, "detail": site.get("detail") or "",
                            "origin_latlng": frame["origin_latlng"], "yaw_deg": frame["yaw_deg"],
                            "outline_area_m2": round(outline_area, 1), "plate_area_m2": round(plate_area, 1),
                            "dropped_m2": round(dropped, 2),
                            "unit_scale": [round(scale_lo, 2), round(scale_hi, 2)] if scale_hi else None}},
    }


class _MovedWalls:
    """Passes interior walls on to the real collector, moved from a unit's own frame to the model's."""

    def __init__(self, walls, move: Callable) -> None:
        self.walls, self.move = walls, move

    def add(self, level: int, a, b, space_id: str, role: str, openings=(), thickness: float = 0.15,
            fidelity: str = "template") -> None:
        self.walls.add(level, self.move(a), self.move(b), space_id, role, openings, thickness=thickness, fidelity=fidelity)


def _move_space(space: Space, move: Callable) -> Space:
    return make_space(space.id, space.level, space.kind, space.label, [move(p) for p in space.polygon], space.fidelity,
                      room_type=space.room_type, raw_class=space.raw_class, parent=space.parent, block=space.block,
                      source_ref=space.source_ref, attrs=dict(space.attrs))


def _inner_box(poly: Polygon, reg: dict) -> Optional[tuple[tuple, Callable]]:
    """The largest box inside a unit that stands on its corridor wall, for the unit's interior.

    Returned in the unit's own frame (x along the corridor, y = 0 at the corridor wall, rooms
    toward +y) with the map from that frame to the plate's. None when nothing useful fits.
    """
    a, vedge, sign = reg["axis"], reg["vedge"], reg["sign"]

    def to_local(p) -> tuple[float, float]:
        return _pt(a, p[0], vedge + sign * p[1])

    pts = [(p[a], (p[1 - a] - vedge) * sign) for p in poly.exterior.coords]
    ua, ub = min(p[0] for p in pts), max(p[0] for p in pts)
    top = max(p[1] for p in pts)
    inside = prep(poly.buffer(0.03, join_style="mitre"))

    def fits(u0: float, u1: float, y0: float, y1: float) -> bool:
        return inside.contains(Polygon([to_local(p) for p in ((u0, y0), (u1, y0), (u1, y1), (u0, y1))]))

    best = None
    for shrink, y0 in ((0.0, 0.0), (0.0, 0.6), (0.15, 0.0), (0.15, 0.6), (0.3, 0.6)):
        u0, u1 = ua + shrink * (ub - ua), ub - shrink * (ub - ua)
        if u1 - u0 < 2.2:
            continue
        if fits(u0, u1, y0, top):
            y1 = top
        else:
            lo, hi = y0, top
            if not fits(u0, u1, y0, y0 + 2.4):
                continue
            lo = y0 + 2.4
            for _ in range(8):
                mid = (lo + hi) / 2
                lo, hi = (mid, hi) if fits(u0, u1, y0, mid) else (lo, mid)
            y1 = lo
        area = (u1 - u0) * (y1 - y0)
        if y1 - y0 >= 2.4 and (best is None or area > best[0]):
            best = (area, (u0, y0, u1, y1))
        if best is not None and shrink == 0.0 and y0 == 0.0:
            break
    return (best[1], to_local) if best else None
