def site_frame(site: dict) -> dict:
    """The model frame for an outline: ``{"origin_latlng", "yaw_deg", "front", "polygons"}``.

    ``polygons`` are the outlines in model metres, largest first. x runs along the long side
    of the rectangle around all of them; of the two ways round, the front (-y) goes toward the
    street, or toward the address point when no street is known.
    """
    from ingest.unified.context import _front_bearing, _gap, oriented_box

    rings = site.get("polygons_latlng") or []
    if not rings:
        raise ShapeError("has no points")
    ref = rings[0][0]
    box_ = oriented_box([latlng_to_local(la, lo, ref) for ring in rings for la, lo in ring])
    origin = [round(v, 7) for v in local_to_latlng(box_["centre"][0], box_["centre"][1], ref)]
    hint = site.get("street_bearing_deg")
    if hint is None and site.get("address_latlng"):
        east, north = latlng_to_local(site["address_latlng"][0], site["address_latlng"][1], origin)
        if math.hypot(east, north) >= 5.0:
            hint = math.degrees(math.atan2(east, north)) % 360.0
    options = [box_["axis_deg"], box_["axis_deg"] + 180.0]
    if hint is not None:
        options.sort(key=lambda a: _gap(_front_bearing(a), hint))
    yaw = round((options[0] + 180.0) % 360.0 - 180.0, 1)
    front = (0.0, -1.0)
    if hint is not None:
        east, north = math.sin(math.radians(hint)), math.cos(math.radians(hint))
        t = math.radians(yaw)
        front = (east * math.cos(t) + north * math.sin(t), -east * math.sin(t) + north * math.cos(t))
    holes = site.get("holes_latlng") or []
    polys = []
    for i, ring in enumerate(rings):
        inner = holes[i] if i < len(holes) else []
        poly = _clean(Polygon([latlng_to_local(la, lo, origin, yaw) for la, lo in ring],
                              [[latlng_to_local(la, lo, origin, yaw) for la, lo in h] for h in inner if len(h) >= 3]))
        if poly is not None:
            polys.append(poly)
    polys.sort(key=lambda p: (-p.area, p.bounds))
    return {"origin_latlng": origin, "yaw_deg": yaw, "front": front, "polygons": polys}


def _natural(key: str):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", key)]


