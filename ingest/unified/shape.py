"""Layer 4, with the real outline: a generated interior inside the building's own shape.

``layout.build_layout`` draws a property as a straight bar sized from its unit list. When
the site context has found the building's outline (Vexcel first, OpenStreetMap second), this
module lays the same record out *inside that outline* instead. What is real is the outline
and, from the record, which units exist, their floor, their order and their relative areas.
Everything else is ``fidelity = "template"``: generated by rule, never measured.

How a plate is laid out
-----------------------
1. **Wings.** The outline is turned so its long side runs along x, then covered greedily with
   the largest rectangles that fit inside it. Each rectangle that is wide enough and joins the
   others end-on becomes a wing: an L gets two, a U three, a courtyard block four.
2. **Corridors.** A wing gets a corridor along its middle (several side by side when the wing is
   much deeper than two rows of units; one against the back wall when it is too thin for two
   rows). Corridors run on to the outline's walls and into the wing they join.
3. **Stairs, elevator, lobby.** Stairs close the corridors' dead ends; a central-core building
   has its stairs beside the elevator instead. The lobby (or, without an elevator, an entry
   passage on the ground floor) is cut from the side whose outer wall best faces the street.
4. **Regions.** What is left of the plate is split into strips, each fronting one corridor.
   Odd corners the rectangles did not cover are joined to the strip they touch.
5. **Units.** A floor's units are dealt to the strips in number order (so consecutive numbers
   face each other across a corridor) and each strip is cut across into units whose areas keep
   the proportions of the record. Nothing is left over: the units are scaled to fill the plate.
6. **Walls, doors, windows, links.** Read off the finished partition: a wall wherever two
   spaces meet, a door where a unit meets its corridor, windows on outer walls.

Frames: the *model* frame has its origin at the centre of the outline's bounding rectangle,
x along its long side and the front (toward the street, when known) at -y. ``origin_latlng``
and ``yaw_deg`` in the returned stats tie it to the ground, so the site context places the
model exactly on the outline with no fitting. A property with several buildings keeps one
model frame; each building is laid out in a frame of its own and moved into it.

Raises ``ShapeError`` when an outline cannot hold the record (too small, too thin, more units
than its walls can front); the caller then falls back to the bar and says so.
"""

