def _shell_walls(polys: dict[str, Polygon]) -> list[tuple[tuple, tuple, tuple]]:
    """Every wall of a floor as ``(a, b, (space, other space or None))``: the outlines of all
    spaces cut where they meet, each piece told which spaces lie on its two sides."""
    ids = list(polys)
    geoms = [polys[i] for i in ids]
    rings = [ring for g in geoms for ring in (g.exterior, *g.interiors)]
    noded = shapely.union_all(rings, grid_size=GRID)
    segs = [(a, b) for ln in _lines(noded) for a, b in zip(ln.coords, ln.coords[1:]) if a != b]
    if not segs:
        return []
    arr = np.array(segs)  # n, 2, 2
    mid = arr.mean(axis=1)
    d = arr[:, 1] - arr[:, 0]
    length = np.hypot(d[:, 0], d[:, 1])
    normal = np.stack([-d[:, 1], d[:, 0]], axis=1) / length[:, None]
    tree = STRtree(geoms)
    sides = []
    for sgn in (1, -1):
        pts = shapely.points(mid + sgn * EPS * normal)
        found = np.full(len(segs), -1)
        qi, ti = tree.query(pts, predicate="within")
        found[qi] = ti
        sides.append(found)
    groups: dict[tuple, list] = defaultdict(list)
    for i, seg in enumerate(segs):
        pair = tuple(sorted(ids[k] for k in (sides[0][i], sides[1][i]) if k >= 0))
        if pair and (len(pair) == 1 or pair[0] != pair[1]):
            groups[pair].append(seg)
    out = []
    for pair in sorted(groups):
        merged = linemerge(MultiLineString(groups[pair]))
        for ln in _lines(merged):
            cs = list(ln.simplify(0.0005).coords)
            out.extend((a, b, pair if len(pair) == 2 else (pair[0], None)) for a, b in zip(cs, cs[1:]))
    return out


