"""Layer 4: an archetype layout for a rostered property. Layer 5 hooks in per unit.

Everything here is ``fidelity = "template"``: plausible geometry generated by rule,
never measured. What is real is which units exist, which floor they are on, their
areas and their order; where a unit sits along the corridor is an assumption (units
are laid out in number order, alternating sides).

Archetypes
----------
``double_loaded_corridor``  a bar: units on both sides of a central corridor, a stair at
                            each end; with an elevator, an elevator and lobby mid-bar
``garden_walkup``           the same bar with an open breezeway instead of an interior
                            corridor and no elevator (low-rise garden apartments)
``central_core``            the bar with stairs and elevators together in the middle
``bays``                    one storey of side-by-side bays that each open to the front
``floor_stack``             no unit data: an undivided plate per floor plus the stairs

A property with several buildings becomes several *blocks* on a grid, joined on the
ground by walkways. A floor with more than ``MAX_UNITS_PER_BAR`` units is split into
parallel *wings* joined by a corridor link on every floor. Stairs and elevators are
template spaces linked floor to floor; nothing about them is taken from a scan.

Local frame: x along the bar, front of the building at low y (see ``schema``).
"""

from __future__ import annotations

import math
import re
from collections import defaultdict
from typing import Callable, Optional

from ingest.unified.schema import Entrance, Level, Link, Opening, Space, Wall, make_space, r, rect, rp

MAX_UNITS_PER_BAR = 36
INTERIOR_MAX_UNITS = 400      # above this, unit interiors are left out to keep the model small
WING_GAP_M = 12.0
BLOCK_GAP_M = 14.0
WALKWAY_M = 3.0
STAIR_W, STAIR_D = 2.8, 5.6
ELEVATOR_W, LOBBY_W = 2.4, 3.2
DOOR_W, DOOR_H = 0.95, 2.05
WINDOW_SILL, WINDOW_HEAD = 0.9, 2.1
MAX_STRETCH = 1.6
STAIR_RUN_M = 6.0

PROFILE = {
    # use type: unit depth, corridor width, default unit area, min unit width
    "apartment": (9.0, 1.8, 70.0, 3.2), "hotel": (8.0, 1.8, 30.0, 3.4), "office": (12.0, 2.0, 150.0, 4.0),
    "healthcare": (10.0, 2.4, 80.0, 3.6), "mixed_use": (10.0, 1.8, 90.0, 3.6), "other": (10.0, 2.0, 100.0, 4.0),
    "retail": (18.0, 0.0, 200.0, 5.0), "industrial": (30.0, 0.0, 800.0, 8.0), "flex": (24.0, 0.0, 400.0, 6.0),
}


def choose_archetype(facts: dict, roster: dict) -> str:
    use, stories = facts.get("use_type") or "other", roster["stories"]
    if not roster["slots"]:
        return "floor_stack"
    if use in ("retail", "industrial", "flex") and stories <= 1:
        return "bays"
    if stories >= 8 or facts.get("style") == "high_rise":
        return "central_core"
    if use == "apartment" and facts.get("has_elevator") is not True and (
            facts.get("style") in ("garden", "townhome") or stories <= 3):
        return "garden_walkup"
    return "double_loaded_corridor"


def _natural(key: str):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", key)]


class _Walls:
    """Collects wall segments, merging the two references to a shared wall."""

    def __init__(self) -> None:
        self.items: dict[tuple, dict] = {}

    def add(self, level: int, a, b, space_id: str, role: str, openings=(), thickness: float = 0.15,
            fidelity: str = "template") -> None:
        pa, pb = rp(a), rp(b)
        if pa == pb:
            return
        flipped = pb < pa
        lo, hi = (pb, pa) if flipped else (pa, pb)
        rec = self.items.setdefault((level, lo, hi), {"spaces": [], "openings": [], "roles": set(),
                                                      "thickness": thickness, "fidelity": fidelity})
        if space_id not in rec["spaces"]:
            rec["spaces"].append(space_id)
        rec["roles"].add(role)
        for o in openings:
            t0, t1 = (1.0 - o.t1, 1.0 - o.t0) if flipped else (o.t0, o.t1)
            rec["openings"].append(Opening(o.kind, r(t0, 4), r(t1, 4), o.z0, o.z1))

    def build(self) -> list[Wall]:
        out = []
        counters: dict[int, int] = defaultdict(int)
        for (level, lo, hi) in sorted(self.items):
            rec = self.items[(level, lo, hi)]
            counters[level] += 1
            inner = rec["roles"] & {"corridor", "partition"}
            out.append(Wall(
                id=f"w{level}-{counters[level]:04d}", level=level, a=lo, b=hi, thickness_m=rec["thickness"],
                exterior=len(rec["spaces"]) == 1 and not inner, open_boundary=False,
                space_ids=tuple(sorted(rec["spaces"])),
                openings=tuple(sorted(set(rec["openings"]), key=lambda o: (o.t0, o.kind))), fidelity=rec["fidelity"],
            ))
        return out


def _opening(kind: str, a, b, at, width: float, z0: float, z1: float) -> Optional[Opening]:
    """An opening of ``width`` centred on the point ``at`` of segment a-b."""
    length = math.dist(a, b)
    if length < width + 0.2:
        width = max(0.4, length - 0.2)
    if length <= 0.5:
        return None
    t = ((at[0] - a[0]) * (b[0] - a[0]) + (at[1] - a[1]) * (b[1] - a[1])) / (length * length)
    half = width / (2 * length)
    t = min(max(t, half + 0.02), 1 - half - 0.02)
    return Opening(kind, r(t - half, 4), r(t + half, 4), r(z0), r(z1))


def generic_interior(slot: dict, box: tuple, corridor_side: str, level: int, z0: float, walls: _Walls) -> list[Space]:
    """Bed / bath layout for a unit with no scan of its type: day rooms on the facade, wet rooms inside."""
    x0, y0, x1, y1 = box
    beds = int(slot.get("beds") or 0)
    baths = max(1, int(math.ceil(float(slot.get("baths") or 1))))
    depth = y1 - y0
    split = y0 + depth * 0.58 if corridor_side == "N" else y1 - depth * 0.58
    facade = (y0, split) if corridor_side == "N" else (split, y1)
    inner = (split, y1) if corridor_side == "N" else (y0, split)
    front = [("liv", "Living Room", 1.5)] + [(f"bed{i + 1}", "Bedroom", 1.0) for i in range(beds)]
    back = ([(f"bath{i + 1}", "Bathroom", 0.8) for i in range(baths)] + [("hall", "Hallway", 0.7), ("kit", "Kitchen", 1.2)])
    out: list[Space] = []
    for band, (ya, yb), is_facade in ((front, facade, True), (back, inner, False)):
        total = sum(w for _, _, w in band)
        x = x0
        for i, (key, cls, weight) in enumerate(band):
            xe = x1 if i == len(band) - 1 else x + (x1 - x0) * weight / total
            sid = f"{slot['id']}/{key}"
            out.append(make_space(sid, level, "room", cls, rect(x, ya, xe, yb), "template", parent=slot["id"],
                                  raw_class=cls, room_type=cls.lower().replace(" ", "_"), block=slot.get("_block", "")))
            if i:  # partition to the previous room of the band
                walls.add(level, (x, ya), (x, yb), sid, "partition", thickness=0.1)
            if is_facade:  # each facade room opens onto the inner band
                a, b = (x, split), (xe, split)
                door = _opening("doorway", a, b, ((x + xe) / 2, split), 0.85, z0, z0 + DOOR_H)
                walls.add(level, a, b, sid, "partition", [door] if door else [], thickness=0.1)
            x = xe
    return out


InteriorFn = Callable[[dict, tuple, str, int, float, float, _Walls], Optional[list[Space]]]


def build_layout(facts: dict, roster: dict, interior: Optional[InteriorFn] = None) -> dict:
    """Spaces, walls, links, entrances and levels for a rostered property.

    ``interior(slot, box, corridor_side, level, z0, height, walls)`` may return the child
    rooms of a unit (Layer 5 stamping); returning None falls back to the generic layout.
    """
    use = facts.get("use_type") or "other"
    depth, corridor_w, default_area, min_w = PROFILE.get(use, PROFILE["other"])
    archetype = choose_archetype(facts, roster)
    stories, h = roster["stories"], roster["storey_height_m"]
    levels = [Level(f, str(f), r((f - 1) * h), r(h), roster["height_source"]) for f in range(1, stories + 1)]
    walls = _Walls()
    spaces: list[Space] = []
    links: list[Link] = []
    entrances: list[Entrance] = []
    notes: list[str] = []
    slots = roster["slots"]
    with_interiors = use in ("apartment", "hotel") and sum(s["kind"] == "unit" for s in slots) <= INTERIOR_MAX_UNITS
    stamped = generic = 0

    def link(a: str, b: str, kind: str, xy=None, length: Optional[float] = None, floors: int = 0) -> None:
        if length is None:
            ca, cb = centre[a], centre[b]
            length = (math.dist(ca, xy) + math.dist(xy, cb)) if xy else math.dist(ca, cb)
        links.append(Link(a=a, b=b, kind=kind, evidence="template", length_m=r(length, 2), floors=floors,
                          xy=rp(xy) if xy else None))

    centre: dict[str, tuple] = {}

    def add(space: Space) -> Space:
        spaces.append(space)
        centre[space.id] = space.centroid
        return space

    def box_walls(level: int, sid: str, box: tuple, roles: dict, openings: dict) -> None:
        x0, y0, x1, y1 = box
        for side, (a, b) in {"S": ((x0, y0), (x1, y0)), "N": ((x0, y1), (x1, y1)),
                             "W": ((x0, y0), (x0, y1)), "E": ((x1, y0), (x1, y1))}.items():
            walls.add(level, a, b, sid, roles.get(side, "side"), openings.get(side, ()))

    blocks: dict[str, list[dict]] = defaultdict(list)
    for s in slots:
        blocks[s["block"]].append(s)
    if not blocks:
        blocks[""] = []
    block_keys = sorted(blocks, key=_natural)

    # ---- size every block first, so they can be placed on a grid -------------
    plans = []
    for bi, key in enumerate(block_keys):
        items = blocks[key]
        per_floor: dict[int, list[dict]] = defaultdict(list)
        for s in items:
            per_floor[s["floor"]].append(s)
        busiest = max((len(v) for v in per_floor.values()), default=0)
        n_wings = max(1, math.ceil(busiest / MAX_UNITS_PER_BAR)) if archetype != "bays" else 1
        wing_floor: list[dict[int, list[dict]]] = [defaultdict(list) for _ in range(n_wings)]
        for f, us in per_floor.items():
            chunk = math.ceil(len(us) / n_wings)
            for i, s in enumerate(us):
                wing_floor[min(i // chunk, n_wings - 1)][f].append(s)
        has_core = archetype == "central_core" or (archetype in ("double_loaded_corridor", "floor_stack") and (
            facts.get("has_elevator") is True or (facts.get("has_elevator") is None and stories >= 4)))
        core_s = (ELEVATOR_W + LOBBY_W) if has_core else 0.0
        core_n = 2 * STAIR_W if archetype == "central_core" else 0.0

        def width(s: dict) -> float:
            return max(min_w, (s.get("area_m2") or default_area) / depth)

        wing_len = []
        for wf in wing_floor:
            longest = 0.0
            for us in wf.values():
                south, north = us[0::2], us[1::2]
                if archetype == "bays":
                    south, north = us, []
                longest = max(longest, sum(map(width, south)) + core_s, sum(map(width, north)) + core_n)
            if not longest:  # no units in this wing: size the plate from the typical floor area
                area = facts.get("typical_floor_m2") or 600.0
                area /= max(1, len(block_keys))
                longest = area / (2 * depth + corridor_w) if archetype != "bays" else area / depth
            wing_len.append(max(12.0, min(longest, 400.0)))
        bar_depth = depth if archetype == "bays" else 2 * depth + corridor_w
        ends = 0.0 if archetype in ("central_core", "bays") else STAIR_W
        plans.append({"key": key, "bi": bi, "wings": wing_floor, "len": wing_len, "has_core": has_core,
                      "core_s": core_s, "core_n": core_n, "ends": ends, "width_fn": width,
                      "w": max(wing_len) + 2 * ends, "d": len(wing_len) * bar_depth + (len(wing_len) - 1) * WING_GAP_M})

    cols = max(1, math.ceil(math.sqrt(len(plans))))
    col_w = max(p["w"] for p in plans) + BLOCK_GAP_M
    y_cursor = 0.0
    walkways: list[str] = []
    for row_start in range(0, len(plans), cols):
        row = plans[row_start:row_start + cols]
        row_y = y_cursor
        walkway_id = None
        if len(plans) > 1 or archetype == "bays":
            walkway_id = f"walk{row_start // cols + 1}"
            add(make_space(walkway_id, 1, "walkway", "Walkway" if archetype != "bays" else "Frontage",
                           rect(-STAIR_W, row_y - WALKWAY_M, len(row) * col_w - BLOCK_GAP_M, row_y), "template"))
            if walkways:
                link(walkways[-1], walkway_id, "walkway")
            walkways.append(walkway_id)
        for ci, plan in enumerate(row):
            ox = ci * col_w
            block = plan["key"]
            tag = f"b{plan['bi'] + 1}"
            prev_corridors: dict[int, str] = {}
            for wi, wing in enumerate(plan["wings"]):
                L = plan["len"][wi]
                oy = row_y + wi * ((depth if archetype == "bays" else 2 * depth + corridor_w) + WING_GAP_M)
                wtag = f"{tag}w{wi + 1}"
                below: dict[str, str] = {}
                for lv in levels:
                    f, z0 = lv.index, lv.z0
                    us = wing.get(f, [])
                    here: dict[str, str] = {}

                    def place_units(units: list[dict], xa: float, xb: float, ya: float, yb: float, corridor_side: str,
                                    row_tag: str) -> None:
                        """Fill [xa, xb] with units in order; leftover length becomes an undivided plate."""
                        nonlocal stamped, generic
                        if xb - xa < 0.5:
                            return
                        widths = [plan["width_fn"](s) for s in units]
                        total = sum(widths)
                        scale = min((xb - xa) / total, MAX_STRETCH) if total else 0.0
                        x = xa
                        for s, w in zip(units, widths):
                            xe = x + w * scale
                            if s is units[-1] and xb - xe < 2.0:
                                xe = xb
                            box = (x, ya, xe, yb)
                            s["_block"] = block
                            unit = add(make_space(
                                s["id"], f, s["kind"], s["label"], rect(*box), "template", block=block,
                                raw_class=s.get("type") or "", room_type="unit" if s["kind"] == "unit" else "suite",
                                source_ref=s["id"],
                                attrs={"beds": s.get("beds"), "baths": s.get("baths"), "tenant": s.get("tenant"),
                                       "floor_source": s.get("floor_source"),
                                       "record_area_m2": round(s["area_m2"], 1) if s.get("area_m2") else None,
                                       "scan": (s.get("scans") or [""])[0]}))
                            door_at = ((x + xe) / 2, yb if corridor_side == "N" else ya)
                            children = None
                            if interior is not None and s.get("scans"):
                                children = interior(s, box, corridor_side, f, z0, lv.height_m, walls)
                            is_stamped = children is not None
                            if children is None and with_interiors and s["kind"] == "unit":
                                children = generic_interior(s, box, corridor_side, f, z0, walls)
                                generic += 1
                            stamped += is_stamped
                            for child in children or []:
                                add(child)
                            facade_side = "S" if corridor_side == "N" else "N"
                            a, b = ((x, yb), (xe, yb)) if corridor_side == "N" else ((x, ya), (xe, ya))
                            door = _opening("doorway", a, b, door_at, DOOR_W, z0, z0 + DOOR_H)
                            fa, fb = ((x, ya), (xe, ya)) if corridor_side == "N" else ((x, yb), (xe, yb))
                            window = None if is_stamped else _opening(
                                "window", fa, fb, ((x + xe) / 2, fa[1]), min(1.8, 0.45 * (xe - x)),
                                z0 + WINDOW_SILL, z0 + WINDOW_HEAD)
                            box_walls(f, s["id"], box, {corridor_side: "corridor", facade_side: "facade"},
                                      {corridor_side: [door] if door else [], facade_side: [window] if window else []})
                            target = here.get("corridor") or walkway_id
                            if archetype == "bays":
                                if walkway_id:
                                    link(s["id"], walkway_id, "door", xy=door_at)
                                if f == 1 and len(entrances) < 12:
                                    entrances.append(Entrance(f"ent-{len(entrances) + 1}", f"{s['label']} front door",
                                                              s["id"], rp(door_at), (0.0, -1.0), "template"))
                            elif target:
                                link(s["id"], target, "door", xy=door_at)
                            x = xe
                        if xb - x >= 2.0:
                            fid = f"{wtag}f{f}-{row_tag}"
                            add(make_space(fid, f, "floor", f"Floor {f} (no unit data)", rect(x, ya, xb, yb), "roster",
                                           block=block, room_type="unknown"))
                            box_walls(f, fid, (x, ya, xb, yb), {corridor_side: "corridor"}, {})
                            if here.get("corridor"):
                                link(fid, here["corridor"], "opening", xy=((x + xb) / 2, yb if corridor_side == "N" else ya))
                            elif walkway_id and f == 1:
                                link(fid, walkway_id, "door", xy=((x + xb) / 2, ya))

                    if archetype == "bays":
                        place_units(us, ox, ox + L, oy, oy + depth, "S", "bay")
                        continue

                    yc0, yc1 = oy + depth, oy + depth + corridor_w
                    cid = f"{wtag}f{f}-cor"
                    here["corridor"] = cid
                    add(make_space(cid, f, "corridor", "Breezeway" if archetype == "garden_walkup" else "Corridor",
                                   rect(ox, yc0, ox + L, yc1), "template", block=block, room_type="corridor"))
                    if wi and f in prev_corridors:  # wings of one building are joined on every floor
                        link(prev_corridors[f], cid, "corridor", length=2 * depth + corridor_w + WING_GAP_M)
                    prev_corridors[f] = cid

                    mid = ox + L / 2
                    south, north = us[0::2], us[1::2]
                    south_segments = [(ox, ox + L)]
                    north_segments = [(ox, ox + L)]
                    if plan["has_core"]:
                        cx0, cx1 = mid - plan["core_s"] / 2, mid + plan["core_s"] / 2
                        south_segments = [(ox, cx0), (cx1, ox + L)]
                        eid, lid = f"{wtag}f{f}-el", f"{wtag}f{f}-lob"
                        add(make_space(eid, f, "elevator", "Elevator", rect(cx0, oy, cx0 + ELEVATOR_W, yc0), "template",
                                       block=block, room_type="elevator"))
                        add(make_space(lid, f, "lobby", "Lobby" if f == 1 else "Elevator lobby",
                                       rect(cx0 + ELEVATOR_W, oy, cx1, yc0), "template", block=block,
                                       room_type="lobby" if f == 1 else "corridor"))
                        lx = (cx0 + ELEVATOR_W + cx1) / 2
                        el_door = _opening("doorway", (cx0, yc0), (cx0 + ELEVATOR_W, yc0), (cx0 + ELEVATOR_W / 2, yc0),
                                           1.1, z0, z0 + DOOR_H)
                        lob_open = _opening("opening", (cx0 + ELEVATOR_W, yc0), (cx1, yc0), (lx, yc0), 2.0, z0, z0 + DOOR_H)
                        front = None
                        if f == 1 and wi == 0:
                            front = _opening("doorway", (cx0 + ELEVATOR_W, oy), (cx1, oy), (lx, oy), 1.6, z0, z0 + DOOR_H)
                            eno = len(entrances) + 1
                            entrances.append(Entrance(f"ent-{eno}", f"Lobby entrance{' ' + block if block else ''}", lid,
                                                      rp((lx, oy)), (0.0, -1.0), "template"))
                            if walkway_id:
                                link(lid, walkway_id, "door", xy=(lx, oy))
                        box_walls(f, eid, (cx0, oy, cx0 + ELEVATOR_W, yc0), {"N": "corridor", "S": "facade"},
                                  {"N": [el_door] if el_door else []})
                        box_walls(f, lid, (cx0 + ELEVATOR_W, oy, cx1, yc0), {"N": "corridor", "S": "facade"},
                                  {"N": [lob_open] if lob_open else [], "S": [front] if front else []})
                        link(eid, cid, "door", xy=(cx0 + ELEVATOR_W / 2, yc0))
                        link(lid, cid, "opening", xy=(lx, yc0))
                        here["elevator"] = eid
                    stair_boxes = []
                    if archetype == "central_core":
                        sx0 = mid - STAIR_W
                        north_segments = [(ox, sx0), (sx0 + 2 * STAIR_W, ox + L)]
                        stair_boxes = [("stA", (sx0, yc1, sx0 + STAIR_W, yc1 + STAIR_D), "S"),
                                       ("stB", (sx0 + STAIR_W, yc1, sx0 + 2 * STAIR_W, yc1 + STAIR_D), "S")]
                    else:
                        ym = (yc0 + yc1) / 2
                        stair_boxes = [("stA", (ox - STAIR_W, ym - STAIR_D / 2, ox, ym + STAIR_D / 2), "E"),
                                       ("stB", (ox + L, ym - STAIR_D / 2, ox + L + STAIR_W, ym + STAIR_D / 2), "W")]
                    for name, sbox, door_side in stair_boxes:
                        sid = f"{wtag}f{f}-{name}"
                        add(make_space(sid, f, "stair", f"Stair {name[-1]}", rect(*sbox), "template", block=block,
                                       room_type="stairwell"))
                        if door_side == "S":
                            a, b = (sbox[0], sbox[1]), (sbox[2], sbox[1])
                            at = ((sbox[0] + sbox[2]) / 2, sbox[1])
                        else:
                            xs = sbox[2] if door_side == "E" else sbox[0]
                            a, b = (xs, yc0), (xs, yc1)
                            at = (xs, (yc0 + yc1) / 2)
                        # the stair door is the corridor's end: an open boundary the width of the corridor
                        door = _opening("doorway", a, b, at, DOOR_W, z0, z0 + DOOR_H)
                        openings = {door_side: [door] if door else []}
                        roles = {door_side: "corridor"}
                        if door_side != "S":
                            # split the stair's corridor-facing side so the doorway sits on the corridor's end wall
                            x0, y0, x1, y1 = sbox
                            walls.add(f, (xs, y0), (xs, yc0), sid, "side")
                            walls.add(f, a, b, sid, "corridor", openings[door_side])
                            walls.add(f, (xs, yc1), (xs, y1), sid, "side")
                            other = x0 if door_side == "E" else x1
                            walls.add(f, (other, y0), (other, y1), sid, "side")
                            walls.add(f, (x0, y0), (x1, y0), sid, "side")
                            walls.add(f, (x0, y1), (x1, y1), sid, "side")
                        else:
                            box_walls(f, sid, sbox, roles, openings)
                        link(sid, cid, "door", xy=at)
                        here[name] = sid
                        if f == 1 and wi == 0 and not plan["has_core"]:
                            ex, ey = (sbox[0] + sbox[2]) / 2, sbox[1]
                            entrances.append(Entrance(f"ent-{len(entrances) + 1}",
                                                      f"Stair {name[-1]} entrance{' ' + block if block else ''}", sid,
                                                      rp((ex, ey)), (0.0, -1.0), "template"))
                            if walkway_id:
                                link(sid, walkway_id, "door", xy=(ex, ey))
                    half = (len(south) + 1) // 2 if len(south_segments) == 2 else len(south)
                    for seg, group in zip(south_segments, (south[:half], south[half:])):
                        place_units(group, seg[0], seg[1], oy, yc0, "N", f"s{south_segments.index(seg)}")
                    half = (len(north) + 1) // 2 if len(north_segments) == 2 else len(north)
                    for seg, group in zip(north_segments, (north[:half], north[half:])):
                        place_units(group, seg[0], seg[1], yc1, yc1 + depth, "S", f"n{north_segments.index(seg)}")
                    for name in ("stA", "stB", "elevator"):
                        if name in here and name in below:
                            link(below[name], here[name], "elevator" if name == "elevator" else "stairs",
                                 length=STAIR_RUN_M if name != "elevator" else lv.height_m, floors=1)
                    below = here
        y_cursor = row_y + max(p["d"] for p in row) + BLOCK_GAP_M + WALKWAY_M

    if archetype == "bays" and not entrances and walkways:
        entrances.append(Entrance("ent-1", "Frontage", walkways[0], (0.0, r(-WALKWAY_M)), (0.0, -1.0), "template"))
    if roster["stats"].get("floor_spread"):
        notes.append(f"{roster['stats']['floor_spread']} unit(s) have no floor in their number; "
                     "they are spread evenly over the floors.")
    recorded = roster["stats"].get("storeys_recorded") or 0
    if recorded and stories > recorded:
        notes.append(f"Unit numbers name floors up to {stories}; the record lists {recorded} storeys. "
                     "The numbers on the doors are used.")
    if len(plans) > 1:
        notes.append(f"{len(plans)} buildings are placed on a grid; their real positions on the site are not in the data.")
    if not with_interiors and use in ("apartment", "hotel"):
        notes.append("Unit interiors are left out for a property this large.")
    notes.append("Unit positions along each corridor are assumed (number order, alternating sides).")
    return {
        "archetype": archetype, "levels": levels, "spaces": spaces, "walls": walls.build(), "links": links,
        "entrances": entrances, "notes": notes,
        "stats": {"blocks": len(plans), "wings": sum(len(p["wings"]) for p in plans),
                  "units_with_stamped_interior": stamped, "units_with_generic_interior": generic},
    }
