"""``BuildingModel``: one shape for surveyed scans, generated buildings and hybrids.

Conventions
-----------
* Metres everywhere. Local frame: x and y are the model's own horizontal axes, z is
  up with z = 0 at the lowest level's floor. For a scan the frame is Matterport's
  model frame; for a generated building x runs along the building and the front
  (the side assumed to face the street) is -y.
* ``Level.index`` is the storey number used everywhere else (1 = lowest level).
* Deterministic: every collection is sorted, every float is rounded at a fixed
  precision, and :meth:`BuildingModel.to_json` is byte-identical for the same input.
  Nothing time-dependent (imagery, road data, timings) is stored here; that lives
  in the ``SiteContext`` sidecar (``ingest.unified.context``).

``fidelity`` says where a piece of geometry comes from, best first:

    surveyed   measured by a Matterport scan of this very space (Track A ``Model3D``)
    traced     drawn by hand over a published floor plan of this very space (``ingest.unified.plan``)
    stamped    measured in a scan of the same unit type, fitted into this unit's slot
    cluster    a scan with no structural layer: position and area only (``ScanModel``)
    template   generated by an archetype rule; plausible, not measured
    roster     known to exist on this level, position unknown
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional

SCHEMA_VERSION = "bm/1"
DP = 3  # coordinates rounded to 1 mm: far below any geometry error here, and keeps the JSON byte-stable

FIDELITY_ORDER = ("surveyed", "traced", "stamped", "cluster", "template", "roster")

# Archetypes that carry their own position and rotation (``geolocation`` is the lat/lng of the
# model's origin, ``yaw_deg`` its rotation): a scan, or a floor plan fitted to map control points.
# Every other archetype is a generated layout that the site context places on the real outline.
SELF_PLACED = ("whole_scan", "scan_clusters", "floor_plan")

# Space kinds. A "unit" / "tenant" is the thing a responder is sent to; a "room" is
# a child of one (or a room of a whole-building scan).
QUERY_KINDS = ("unit", "tenant", "room", "floor")
SHARED_KINDS = ("corridor", "stair", "elevator", "lobby", "amenity", "walkway", "parking")

Point = tuple[float, float]


def r(value: float, dp: int = DP) -> float:
    """Round and normalise -0.0 so the JSON never differs by sign of zero."""
    out = round(float(value), dp)
    return 0.0 if out == 0 else out


def rp(point) -> Point:
    return (r(point[0]), r(point[1]))


@dataclass(frozen=True)
class Level:
    index: int
    label: str
    z0: float
    height_m: float
    # doorway-median | pano-z-fallback (scan slabs) | scan | plan | assumed | building | record | default
    source: str


@dataclass(frozen=True)
class Opening:
    """A hole in a wall: ``t`` is a fraction along the wall, ``z`` is metres on the model datum."""

    kind: str  # doorway | window | opening | divider
    t0: float
    t1: float
    z0: float
    z1: float


@dataclass(frozen=True)
class Space:
    id: str
    level: int
    kind: str
    label: str
    polygon: tuple[Point, ...]
    centroid: Point
    area_m2: float
    fidelity: str
    room_type: str = ""          # clue-vocabulary room type, when one applies
    raw_class: str = ""          # the source's own label (Matterport class, unit type name)
    parent: Optional[str] = None  # the unit / tenant a room belongs to
    block: str = ""              # building or wing within the property
    source_ref: str = ""         # Matterport model id / room id, or property unit id
    attrs: tuple[tuple[str, str], ...] = ()  # small sorted extras: beds, baths, tenant, floor_source ...


@dataclass(frozen=True)
class Wall:
    id: str
    level: int
    a: Point
    b: Point
    thickness_m: float
    exterior: bool
    open_boundary: bool
    space_ids: tuple[str, ...]
    openings: tuple[Opening, ...]
    fidelity: str


@dataclass(frozen=True)
class Link:
    """Two spaces a person can walk between."""

    a: str
    b: str
    kind: str      # door | opening | corridor | stairs | elevator | walkway
    evidence: str  # opening | scan-graph | template | inferred | plan | building
    length_m: float
    floors: int = 0
    xy: Optional[Point] = None


@dataclass(frozen=True)
class Entrance:
    id: str
    name: str
    space_id: str
    xy: Point
    outward: Point  # unit vector pointing out of the building at the door
    evidence: str


@dataclass(frozen=True)
class BuildingModel:
    schema: str
    id: str
    name: str
    address: str
    use_type: str
    archetype: str
    tier: str
    yaw_deg: float
    geolocation: Optional[Point]
    levels: tuple[Level, ...]
    spaces: tuple[Space, ...]
    walls: tuple[Wall, ...]
    links: tuple[Link, ...]
    entrances: tuple[Entrance, ...]
    stats: dict
    notes: tuple[str, ...] = field(default_factory=tuple)

    def level(self, index: int) -> Optional[Level]:
        for lv in self.levels:
            if lv.index == index:
                return lv
        return None

    def to_dict(self) -> dict:
        return asdict(self)

    def to_json(self, indent: Optional[int] = None) -> str:
        return json.dumps(self.to_dict(), indent=indent, sort_keys=True, ensure_ascii=True,
                          separators=(",", ":") if indent is None else None)

    def to_json_file(self, path: str | Path) -> Path:
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(self.to_json(), encoding="utf-8", newline="\n")
        return target


def polygon_area(polygon) -> float:
    n = len(polygon)
    return abs(sum(polygon[i][0] * polygon[(i + 1) % n][1] - polygon[(i + 1) % n][0] * polygon[i][1]
                   for i in range(n))) / 2.0


def polygon_centroid(polygon) -> Point:
    n = len(polygon)
    a = cx = cy = 0.0
    for i in range(n):
        x0, y0 = polygon[i]
        x1, y1 = polygon[(i + 1) % n]
        cross = x0 * y1 - x1 * y0
        a += cross
        cx += (x0 + x1) * cross
        cy += (y0 + y1) * cross
    if abs(a) < 1e-9:
        return (sum(p[0] for p in polygon) / n, sum(p[1] for p in polygon) / n)
    return (cx / (3 * a), cy / (3 * a))


def make_space(space_id: str, level: int, kind: str, label: str, polygon, fidelity: str, **extra) -> Space:
    poly = tuple(rp(p) for p in polygon)
    attrs = extra.pop("attrs", None) or {}
    return Space(
        id=space_id, level=level, kind=kind, label=label, polygon=poly,
        centroid=rp(polygon_centroid(poly)), area_m2=r(polygon_area(poly), 2), fidelity=fidelity,
        attrs=tuple(sorted((str(k), str(v)) for k, v in attrs.items() if v not in (None, ""))),
        **extra,
    )


def rect(x0: float, y0: float, x1: float, y1: float) -> list[Point]:
    """Counter-clockwise rectangle."""
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
